/** Shared deterministic discovery policy. Original questions and Evidence stay intact. */
export function retrievalConcepts(texts: readonly string[]): string[] {
  let remaining = MAX_INPUT_CHARACTERS;
  const concepts: string[] = [];
  const seen = new Set<string>();
  for (const text of texts) {
    if (!remaining || concepts.length >= MAX_CONCEPTS) break;
    const bounded = text.slice(0, remaining);
    remaining -= bounded.length;
    for (const match of bounded.matchAll(/[\p{L}\p{N}][\p{L}\p{N}_./-]{0,79}/gu)) {
      const term = match[0].replace(/[./-]+$/u, "");
      const key = term.toLowerCase();
      if (term.length < 2 || STOP_WORDS.has(key) || seen.has(key)) continue;
      seen.add(key);
      concepts.push(term);
      if (concepts.length >= MAX_CONCEPTS) break;
    }
  }
  return concepts;
}
